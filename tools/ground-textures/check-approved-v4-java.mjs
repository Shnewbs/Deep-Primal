import fs from 'node:fs';
import path from 'node:path';
import {execFileSync as run} from 'node:child_process';
const [repo,jdk]=process.argv.slice(2);
if(!repo||!jdk)throw Error('Usage: node check-approved-v4-java.mjs REPO JDK_DIRECTORY');
const source=fs.readFileSync(path.join(repo,'src/main/java/com/shnewbs/deepprimal/client/GroundSideSpriteSource.java'),'utf8');
const start=source.indexOf('  public static int pack('),end=source.indexOf('  /** Alpha stores',start);
if(start<0||end<start)throw Error('Material method markers changed; inspect before updating extraction');
const work=path.join(repo,'build/ground-v4-image-checks');fs.mkdirSync(work,{recursive:true});
const math=path.join(work,'MaterialMath.java');
fs.writeFileSync(math,'public final class MaterialMath {\n'+source.slice(start,end)+'\n}\n');
run(path.join(jdk,'bin/javac'),['-d',work,math,path.join(repo,'tools/ground-textures/ApprovedV4ImageChecks.java')],{stdio:'inherit'});
run(path.join(jdk,'bin/java'),['-cp',work,'ApprovedV4ImageChecks',path.join(repo,'src/main/resources/assets/deepprimal/textures/block/ground')],{stdio:'inherit'});
