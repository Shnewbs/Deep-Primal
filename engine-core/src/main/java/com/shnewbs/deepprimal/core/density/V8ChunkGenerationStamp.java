package com.shnewbs.deepprimal.core.density;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;
import java.util.zip.CRC32;

/**
 * Versioned per-chunk V8 generation identity, suitable for an authoritative
 * native chunk-data owner to persist after successful materialization.
 * This class does not read/write NBT or declare a chunk committed: the native
 * owner must atomically publish the encoded stamp with its completed chunk.
 */
public final class V8ChunkGenerationStamp {
  private V8ChunkGenerationStamp() {}

  private static final String PREFIX = "dp-v8-chunk/1";

  public record Stamp(int revision, int chunkX, int chunkZ, long profileFingerprint) {
    public Stamp {
      if (revision < 2 || revision > 6)
        throw new IllegalArgumentException("explicit V8 generation revision 2..6 required");
      if (profileFingerprint == 0L)
        throw new IllegalArgumentException("missing saved V8 profile identity");
    }

    /** Canonical ASCII payload; CRC detects torn/corrupted storage, not forgery. */
    public String encode() {
      String body = PREFIX + "|" + revision + "|" + chunkX + "|" + chunkZ + "|"
          + String.format(java.util.Locale.ROOT, "%016x", profileFingerprint);
      return body + "|" + String.format(java.util.Locale.ROOT, "%08x", crc(body));
    }
  }

  public static Stamp decode(String encoded) {
    Objects.requireNonNull(encoded, "encoded V8 chunk identity");
    if (encoded.length() > 96)
      throw new IllegalArgumentException("oversized V8 chunk identity");
    String[] parts = encoded.split("\\|", -1);
    if (parts.length != 6 || !PREFIX.equals(parts[0])
        || !parts[4].matches("[0-9a-f]{16}") || !parts[5].matches("[0-9a-f]{8}"))
      throw new IllegalArgumentException("invalid V8 chunk identity envelope");
    try {
      Stamp stamp = new Stamp(Integer.parseInt(parts[1]), Integer.parseInt(parts[2]),
          Integer.parseInt(parts[3]), Long.parseUnsignedLong(parts[4], 16));
      if (!stamp.encode().equals(encoded))
        throw new IllegalArgumentException("noncanonical or corrupt V8 chunk identity");
      return stamp;
    } catch (NumberFormatException error) {
      throw new IllegalArgumentException("invalid V8 chunk identity number", error);
    }
  }

  private static long crc(String value) {
    CRC32 sum = new CRC32();
    byte[] bytes = value.getBytes(StandardCharsets.US_ASCII);
    sum.update(bytes, 0, bytes.length);
    return sum.getValue();
  }

  /** A native owner must distinguish an absent stamp from an unreadable chunk. */
  public record Observation(V8GenerationBorderAdmission.Direction direction,
                            V8GenerationBorderAdmission.State state, String persistedStamp) {
    public Observation {
      Objects.requireNonNull(direction, "direction");
      Objects.requireNonNull(state, "state");
    }
  }

  /**
   * Build the existing border gate only from persisted, revision-checked
   * observations. The target must be authoritatively UNGENERATED. Unknown,
   * legacy, edited or mismatched neighbors fail before native materialization.
   * No neighboring chunks are loaded or generated by this method.
   */
  public static V8GenerationBorderAdmission.Witness witnessForNewChunk(
      Stamp intended, V8GenerationBorderAdmission.State targetState,
      String targetPersistedStamp, List<Observation> observations) {
    Objects.requireNonNull(intended, "intended stamp");
    if (targetState != V8GenerationBorderAdmission.State.UNGENERATED
        || targetPersistedStamp != null)
      throw new IllegalArgumentException("V8 destination is not certified ungenerated");
    Objects.requireNonNull(observations, "observations");
    List<V8GenerationBorderAdmission.Neighbor> neighbors = new ArrayList<>(4);
    for (Observation observed : List.copyOf(observations)) {
      int x, z;
      try {
        x = Math.addExact(intended.chunkX(), switch (observed.direction()) {
          case EAST -> 1;
          case WEST -> -1;
          default -> 0;
        });
        z = Math.addExact(intended.chunkZ(), switch (observed.direction()) {
          case SOUTH -> 1;
          case NORTH -> -1;
          default -> 0;
        });
      } catch (ArithmeticException overflow) {
        throw new IllegalArgumentException("V8 border coordinate overflow", overflow);
      }
      long identity = 0L;
      if (observed.state() == V8GenerationBorderAdmission.State.GENERATED) {
        Stamp neighbor = decode(observed.persistedStamp());
        if (neighbor.revision() != intended.revision()
            || neighbor.chunkX() != x || neighbor.chunkZ() != z
            || neighbor.profileFingerprint() != intended.profileFingerprint())
          throw new IllegalArgumentException("incompatible persisted V8 neighbor");
        identity = neighbor.profileFingerprint();
      } else if (observed.state() != V8GenerationBorderAdmission.State.UNGENERATED
          || observed.persistedStamp() != null) {
        throw new IllegalArgumentException("unknown or stamped ungenerated V8 neighbor");
      }
      neighbors.add(new V8GenerationBorderAdmission.Neighbor(
          observed.direction(), x, z, observed.state(), identity));
    }
    var witness = new V8GenerationBorderAdmission.Witness(
        intended.chunkX(), intended.chunkZ(), intended.profileFingerprint(), neighbors);
    V8GenerationBorderAdmission.requireCompatible(witness,
        intended.chunkX(), intended.chunkZ(), intended.profileFingerprint());
    return witness;
  }
}
