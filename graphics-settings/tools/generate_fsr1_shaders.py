#!/usr/bin/env python3
"""Reproduce the GLSL 330 FSR 1 kernels from the pinned, unmodified AMD headers.

Requires a C preprocessor (cpp). Shader generation is a maintenance operation;
neither building nor running the game requires Python or a C toolchain.
"""
from pathlib import Path
import re
import subprocess

MODULE = Path(__file__).resolve().parents[1]
SHADERS = MODULE / "src/main/resources/assets/deepprimal_graphics/shaders"
VENDOR = SHADERS / "upscaling/vendor"
COMMIT = "a21ffb8f6c13233ba336352bdff293894c706575"


def kernel(entry: str) -> str:
    source = "\n".join((
        "#define A_GPU 1", "#define A_GLSL 1", "#define FSR_EASU_F 1",
        "#define FSR_RCAS_F 1", '#include "ffx_a.h"', '#include "ffx_fsr1.h"', "",
    ))
    expanded = subprocess.run(
        ["cpp", "-P", "-undef", "-x", "c", "-I", str(VENDOR)],
        input=source, text=True, capture_output=True, check=True,
    ).stdout
    functions = {}
    overloaded = set()
    signature = re.compile(r"\b(?:void|float|vec[234]|uint|uvec[234]|int|ivec[234]|bool)\s+(\w+)\s*\([^;{}]*\)\s*\{")
    for match in signature.finditer(expanded):
        end = match.end()
        depth = 1
        while depth:
            depth += (expanded[end] == "{") - (expanded[end] == "}")
            end += 1
        name = match.group(1)
        if name in functions:
            overloaded.add(name)
        functions[name] = expanded[match.start():end]
    reachable = {entry}
    pending = [entry]
    while pending:
        name = pending.pop()
        if name in overloaded:
            raise ValueError("Reachable overloaded AMD helper: " + name)
        for called in re.findall(r"\b(\w+)\s*\(", functions[name]):
            if called in functions and called not in reachable:
                reachable.add(called)
                pending.append(called)
    code = "\n\n".join(body for name, body in functions.items() if name in reachable)
    # The bundled Vulkan GLSL converter treats bare function-parameter `out`
    # as a stage output. Delay this token until the real shader preprocessor.
    # This changes no GLSL semantics and also works on the OpenGL backend.
    return re.sub(r"\bout\b", "FSR_OUT", code)


LICENSE = "\n".join("// " + line for line in (VENDOR / "license.txt").read_text().splitlines())
# The portability header contains this additional notice for approximation concepts.
A_HEADER = (VENDOR / "ffx_a.h").read_text()
MICHAL = A_HEADER[A_HEADER.index("// MIT LICENSE"):A_HEADER.index("// ABOUT")]
PREAMBLE = f"""#version 330
// Generated by graphics-settings/tools/generate_fsr1_shaders.py.
// AMD FidelityFX-FSR upstream commit {COMMIT}.
// The AMD FP32 kernels below are preprocessed verbatim, with unused helpers omitted.
{LICENSE}
{MICHAL}
#define FSR_OUT out
uniform sampler2D Source;
out vec4 fragColor;
"""

EASU_INPUT = """
layout(std140) uniform FsrEasu {
    vec4 EasuCon0;
    vec4 EasuCon1;
    vec4 EasuCon2;
    vec4 EasuCon3;
};

// Equivalent to GLSL textureGather's component order. Explicit texel reads
// preserve the official EASU input contract on OpenGL 3.3 without extensions.
// The four callbacks' identical loads are eligible for shader compiler CSE.
vec4 fsrGather(vec2 p, int channel) {
    ivec2 size = textureSize(Source, 0);
    ivec2 base = ivec2(floor(p * vec2(size) - 0.5));
    ivec2 limit = size - ivec2(1);
    return vec4(
        texelFetch(Source, clamp(base + ivec2(0, 1), ivec2(0), limit), 0)[channel],
        texelFetch(Source, clamp(base + ivec2(1, 1), ivec2(0), limit), 0)[channel],
        texelFetch(Source, clamp(base + ivec2(1, 0), ivec2(0), limit), 0)[channel],
        texelFetch(Source, clamp(base, ivec2(0), limit), 0)[channel]);
}
vec4 FsrEasuRF(vec2 p) { return fsrGather(p, 0); }
vec4 FsrEasuGF(vec2 p) { return fsrGather(p, 1); }
vec4 FsrEasuBF(vec2 p) { return fsrGather(p, 2); }
"""
EASU_MAIN = """
void main() {
    vec3 color;
    FsrEasuF(color, uvec2(gl_FragCoord.xy), floatBitsToUint(EasuCon0),
             floatBitsToUint(EasuCon1), floatBitsToUint(EasuCon2),
             floatBitsToUint(EasuCon3));
    fragColor = vec4(color, 1.0);
}
"""
RCAS_INPUT = """
layout(std140) uniform FsrRcas {
    vec4 Sharpness;
};
vec4 FsrRcasLoadF(ivec2 p) {
    return texelFetch(Source, clamp(p, ivec2(0), textureSize(Source, 0) - ivec2(1)), 0);
}
void FsrRcasInputF(inout float r, inout float g, inout float b) {}
"""
RCAS_MAIN = """
void main() {
    vec3 color;
    // FsrRcasCon stores exp2(-stops) in con.x. The UI supplies that same
    // linear weight directly, giving continuous 0 = off, 1 = maximum strength.
    uvec4 con = uvec4(floatBitsToUint(Sharpness.x), 0u, 0u, 0u);
    FsrRcasF(color.r, color.g, color.b, uvec2(gl_FragCoord.xy), con);
    fragColor = vec4(color, 1.0);
}
"""


def main() -> None:
    output = SHADERS / "core"
    output.mkdir(parents=True, exist_ok=True)
    for name, entry, inputs, body in (
        ("fsr_easu", "FsrEasuF", EASU_INPUT, EASU_MAIN),
        ("fsr_rcas", "FsrRcasF", RCAS_INPUT, RCAS_MAIN),
    ):
        (output / (name + ".fsh")).write_text(PREAMBLE + inputs + "\n" + kernel(entry) + "\n" + body)


if __name__ == "__main__":
    main()
